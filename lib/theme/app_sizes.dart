/// Defines standardized sizing constants for consistent retro styling across the application.
class AppSizes {
  /// Standard icon size used within list tiles.
  static const double icon = 28.0;

  /// Icon size used in the bottom navigation bar.
  static const double navIcon = 30.0;

  /// Headline font size used for AppBars and primary list tile titles.
  static const double title = 28.0;

  /// Subtitle font size for secondary labels and descriptions.
  static const double subtitle = 15.0;

  /// Font size for bottom navigation item labels.
  static const double navLabel = 14.0;

  /// Total height of the bottom navigation bar.
  static const double navHeight = 74.0;

  /// Standard horizontal padding for list tiles.
  static const double listPaddingHorizontal = 22.0;

  /// Vertical spacing between distinct sections in lists.
  static const double sectionSpacing = 20.0;
}
